#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
FAILURE_RETRIES="${BROWSER_USE_EVAL_FAILURE_RETRIES:-1}"
SAMPLE_MS="${BROWSER_USE_EVAL_SAMPLE_INTERVAL_MS:-100}"
SETTLE_MS="${BROWSER_USE_EVAL_SETTLE_MS:-1500}"
CPUS="${BROWSER_USE_EVAL_CPUS:-2}"
MEMORY="${BROWSER_USE_EVAL_MEMORY:-2g}"
BUILD_IMAGES="${BROWSER_USE_EVAL_BUILD_IMAGES:-1}"
LLM_DIAGNOSTICS="${BROWSER_USE_EVAL_LLM_DIAGNOSTICS:-0}"
DIAGNOSIS_MODEL="${BROWSER_USE_EVAL_DIAGNOSIS_MODEL:-gpt-5.6-sol}"
DIAGNOSIS_EFFORT="${BROWSER_USE_EVAL_DIAGNOSIS_REASONING_EFFORT:-low}"
DATA_HOME="${BROWSER_EVAL_DATA_HOME:-${HOME}/.browser-eval}"
OUTPUT="${BROWSER_USE_EVAL_OUTPUT_DIR:-${DATA_HOME}/trajectory-replay/runs/$(date -u +%Y%m%dT%H%M%SZ)-$$}"
if [[ "${OUTPUT}" != /* ]]; then
  OUTPUT="${PWD}/${OUTPUT}"
fi
REPORTS="${OUTPUT}/report"

if [[ -e "${OUTPUT}" || -L "${OUTPUT}" ]]; then
  echo "Output must be a new directory; existing evidence is immutable: ${OUTPUT}" >&2
  exit 2
fi
cd "${ROOT}"

command -v docker >/dev/null 2>&1 || { echo "docker is required" >&2; exit 2; }
command -v uv >/dev/null 2>&1 || { echo "uv is required" >&2; exit 2; }
OUTPUT="$(uv run --frozen --extra browser-use-eval python -c \
  'import sys; from pathlib import Path; from harness.web_fetch.safety import unlinked_path; print(unlinked_path(Path(sys.argv[1])))' \
  "${OUTPUT}")"
REPORTS="${OUTPUT}/report"
docker info >/dev/null

mkdir -p "$(dirname "${OUTPUT}")"
echo "Evidence directory: ${OUTPUT}"

if [[ "${BUILD_IMAGES}" == "1" ]]; then
  docker build -f "${ROOT}/examples/trajectory_replay/docker/chromium.Dockerfile" \
    -t lex-browser-use-eval-chromium:local "${ROOT}"
  docker build -f "${ROOT}/examples/trajectory_replay/docker/moli.Dockerfile" \
    -t lex-browser-use-eval-moli:local "${ROOT}"
fi

RUNNER=(uv run --frozen --extra browser-use-eval python)

EXTRA_ARGS=(--diagnosis-model "${DIAGNOSIS_MODEL}" \
  --diagnosis-reasoning-effort "${DIAGNOSIS_EFFORT}")
if [[ "${LLM_DIAGNOSTICS}" == "1" ]]; then
  EXTRA_ARGS+=(--llm-diagnostics)
fi

"${RUNNER[@]}" -m harness.trajectory_replay.cli \
  --suite "${ROOT}/examples/trajectory_replay/tasks.v4.json" \
  --output "${OUTPUT}" \
  --reports "${REPORTS}" \
  --ground-truth-evidence "${ROOT}/examples/trajectory_replay/ground_truth_validation.json" \
  --failure-retries "${FAILURE_RETRIES}" \
  --sample-interval-ms "${SAMPLE_MS}" \
  --settle-ms "${SETTLE_MS}" \
  --cpus "${CPUS}" \
  --memory "${MEMORY}" \
  "${EXTRA_ARGS[@]}"

"${RUNNER[@]}" "${ROOT}/examples/trajectory_replay/verify_metrics.py" --artifacts "${OUTPUT}"

echo "Raw artifacts: ${OUTPUT}"
echo "Latest report: ${REPORTS}/trajectory-replay-evaluation-latest.html"
echo "All metrics and HTML above were generated by repository code; Codex is not part of scoring or calculation."
