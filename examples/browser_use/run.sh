#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
PYTHON="${BROWSER_USE_EVAL_PYTHON:-python3}"
VENV="${BROWSER_USE_EVAL_VENV:-${ROOT}/.browser-use-eval-venv}"
FAILURE_RETRIES="${BROWSER_USE_EVAL_FAILURE_RETRIES:-1}"
SAMPLE_MS="${BROWSER_USE_EVAL_SAMPLE_INTERVAL_MS:-100}"
SETTLE_MS="${BROWSER_USE_EVAL_SETTLE_MS:-1500}"
CPUS="${BROWSER_USE_EVAL_CPUS:-2}"
MEMORY="${BROWSER_USE_EVAL_MEMORY:-2g}"
BUILD_IMAGES="${BROWSER_USE_EVAL_BUILD_IMAGES:-1}"
LLM_DIAGNOSTICS="${BROWSER_USE_EVAL_LLM_DIAGNOSTICS:-0}"
DIAGNOSIS_MODEL="${BROWSER_USE_EVAL_DIAGNOSIS_MODEL:-gpt-5.6-sol}"
DIAGNOSIS_EFFORT="${BROWSER_USE_EVAL_DIAGNOSIS_REASONING_EFFORT:-low}"
OUTPUT="${BROWSER_USE_EVAL_OUTPUT_DIR:-${ROOT}/artifacts/browser_use/latest}"
REPORTS="${ROOT}/docs/reports"

command -v docker >/dev/null 2>&1 || { echo "docker is required" >&2; exit 2; }
command -v "${PYTHON}" >/dev/null 2>&1 || { echo "${PYTHON} is required" >&2; exit 2; }
docker info >/dev/null

if ! "${PYTHON}" -m venv --help >/dev/null 2>&1; then
  echo "Python venv support is required (Ubuntu/Debian: sudo apt-get install python3-venv)" >&2
  exit 2
fi

mkdir -p "${OUTPUT}" "${REPORTS}"
find "${OUTPUT}" -mindepth 1 -maxdepth 1 -type f -delete

if [[ "${BUILD_IMAGES}" == "1" ]]; then
  docker build -f "${ROOT}/examples/browser_use/docker/chromium.Dockerfile" \
    -t lex-browser-use-eval-chromium:local "${ROOT}"
  docker build -f "${ROOT}/examples/browser_use/docker/moli.Dockerfile" \
    -t lex-browser-use-eval-moli:local "${ROOT}"
fi

if command -v uv >/dev/null 2>&1; then
  RUNNER=(uv run --extra browser-use-eval python)
else
  if [[ ! -x "${VENV}/bin/python" ]]; then
    if ! "${PYTHON}" -m venv "${VENV}"; then
      echo "Failed to create venv (Ubuntu/Debian: sudo apt-get install python3-venv)" >&2
      exit 2
    fi
  fi
  if ! "${VENV}/bin/python" -m pip --version >/dev/null 2>&1; then
    "${PYTHON}" -m ensurepip --upgrade
  fi
  "${VENV}/bin/python" -m pip install --disable-pip-version-check -q \
    -e "${ROOT}[browser-use-eval]"
  RUNNER=("${VENV}/bin/python")
fi

EXTRA_ARGS=(--diagnosis-model "${DIAGNOSIS_MODEL}" \
  --diagnosis-reasoning-effort "${DIAGNOSIS_EFFORT}")
if [[ "${LLM_DIAGNOSTICS}" == "1" ]]; then
  EXTRA_ARGS+=(--llm-diagnostics)
fi

"${RUNNER[@]}" -m harness.browser_use.cli \
  --suite "${ROOT}/examples/browser_use/tasks.v4.json" \
  --output "${OUTPUT}" \
  --reports "${REPORTS}" \
  --ground-truth-evidence "${ROOT}/examples/browser_use/ground_truth_validation.json" \
  --failure-retries "${FAILURE_RETRIES}" \
  --sample-interval-ms "${SAMPLE_MS}" \
  --settle-ms "${SETTLE_MS}" \
  --cpus "${CPUS}" \
  --memory "${MEMORY}" \
  "${EXTRA_ARGS[@]}"

echo "Raw artifacts: ${OUTPUT}"
echo "Latest report: ${REPORTS}/browser-use-evaluation-latest.html"
echo "All metrics and HTML above were generated by repository code; Codex is not part of scoring or calculation."
